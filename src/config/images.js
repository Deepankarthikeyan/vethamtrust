const VETHAM_ASSET_VERSION = 'founders-uniform-v3';

export function img(key) {
  const entry = catalog[key];
  if (!entry) return '';
  const src = entry[0];
  if (src.startsWith('/assets/images/vetham/')) {
    return `${src}?v=${VETHAM_ASSET_VERSION}`;
  }
  return src;
}

export function imgCdn(key) {
  return img(key);
}

